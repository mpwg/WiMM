import { test, expect } from '@playwright/test'
test('application shell and health endpoints', async ({ page, request }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { level: 1 })).toContainText('Einnahmen und Ausgaben')
  await expect(page.getByRole('link', { name: 'Anmelden' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  const live = await request.get('/health/live')
  expect(live.status()).toBe(200)
  expect(live.headers()['x-request-id']).toMatch(/^[0-9a-f-]{36}$/)
  await expect(page.locator('link[rel=manifest]')).toHaveAttribute('href', '/manifest.webmanifest')
  const manifest = await request.get('/manifest.webmanifest')
  expect(await manifest.json()).toMatchObject({ display: 'standalone', start_url: '/', scope: '/' })
  const auth = await request.get('/auth/oidc', { maxRedirects: 0 })
  expect(auth.status()).toBe(302)
  expect(auth.headers()['referrer-policy']).toBe('no-referrer')
  const session = await request.get('/api/session')
  expect(session.status()).toBe(401)
  expect(session.headers()['cache-control']).toBe('no-store')
  expect((await session.json()).error.code).toBe('unauthenticated')
  expect((await request.get('/api/_auth/session')).status()).toBe(404)
  expect((await request.get('/api/_auth')).status()).toBe(404)
  const ready = await request.get('/health/ready')
  expect(ready.status()).toBe(200)
  expect(ready.headers()['cache-control']).toBe('no-store')
})
